@Composable
fun PasswordGeneratorDialog(onDismiss: () -> Unit, onUse: (String) -> Unit) {
    var options by remember { mutableStateOf(PasswordGeneratorOptions()) }
    var generated by remember { mutableStateOf("") }
    val hasCharacterType = options.lowercase || options.uppercase || options.numbers || options.symbols

    LaunchedEffect(options) {
        generated = if (hasCharacterType) generateRandomPassword(options) else ""
    }

    AlertDialog(
        onDismissRequest = onDismiss,
        icon = { Icon(Icons.Outlined.AutoAwesome, contentDescription = null, tint = LockrColors.Accent) },
        title = { Text("Generate password", style = MaterialTheme.typography.titleLarge, color = LockrColors.TextPrimary) },
        text = {
            Column(verticalArrangement = Arrangement.spacedBy(8.dp)) {
                Row(Modifier.fillMaxWidth(), verticalAlignment = Alignment.CenterVertically,
                    horizontalArrangement = Arrangement.SpaceBetween) {
                    Text("Preview", style = MaterialTheme.typography.labelMedium,
                        color = LockrColors.TextSecondary)
                    TextButton(onClick = { generated = generateRandomPassword(options) }, enabled = hasCharacterType) {
                        Text("Regenerate")
                    }
                }
                Text(
                    generated.ifEmpty { "Choose a character type" },
                    style = MaterialTheme.typography.bodyMedium.copy(fontSize = 14.sp),
                    color = LockrColors.TextPrimary,
                    maxLines = 3,
                    overflow = TextOverflow.Ellipsis
                )
                Column(Modifier.heightIn(max = 390.dp).verticalScroll(rememberScrollState()),
                    verticalArrangement = Arrangement.spacedBy(8.dp)) {
                    Text("Length: ${options.length}", style = MaterialTheme.typography.titleSmall,
                        color = LockrColors.TextPrimary)
                    Slider(
                        value = options.length.toFloat(),
                        onValueChange = { options = options.copy(length = it.toInt().coerceIn(8, 64)) },
                        valueRange = 8f..64f,
                        steps = 0
                    )
                    GeneratorSwitch("Lowercase letters", options.lowercase) { options = options.copy(lowercase = it) }
                    GeneratorSwitch("Uppercase letters", options.uppercase) { options = options.copy(uppercase = it) }
                    GeneratorSwitch("Numbers", options.numbers) { options = options.copy(numbers = it) }
                    GeneratorSwitch("Symbols", options.symbols) { options = options.copy(symbols = it) }
                    GeneratorSwitch("Mix selected types", options.mixSelectedTypes) { options = options.copy(mixSelectedTypes = it) }
                }
                if (!hasCharacterType) {
                    Text("Choose at least one character type.", color = Color(0xFFB83F45), style = MaterialTheme.typography.bodySmall)
                }
            }
        },
        confirmButton = {
            Button(onClick = { onUse(generated) }, enabled = generated.isNotEmpty()) { Text("Use password") }
        },
        dismissButton = { TextButton(onClick = onDismiss) { Text("Cancel") } },
        containerColor = LockrColors.Surface,
        shape = RoundedCornerShape(26.dp)
    )
}

@Composable
private fun GeneratorSwitch(label: String, checked: Boolean, onCheckedChange: (Boolean) -> Unit) {
    Row(Modifier.fillMaxWidth(), verticalAlignment = Alignment.CenterVertically,
        horizontalArrangement = Arrangement.SpaceBetween) {
        Text(label, style = MaterialTheme.typography.bodyMedium, color = LockrColors.TextPrimary,
            modifier = Modifier.weight(1f))
        Switch(checked = checked, onCheckedChange = onCheckedChange)
    }
}
